# Voir la version
npm -v

# Installer une nouvelle dépendance sur le projet (dans le répertoire du projet, à la racine)
# Toutes les dépendances du projet seront dans un répertoire node_modules
npm install nom_dependance
npm i nom_dependance

# Installer les dépendances manquantes au projet (dans le répertoire du projet)
npm install
npm i

# Installer une "application" de manière générale sur l'ordinateur
npm install -g nom_dependance
npm i -g nom_dependance
